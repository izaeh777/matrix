function esc(v) {
	return String(v).replace(/\\/g, '\\\\').replace(/'/g, "\\'").replace(/\r/g, '').replace(/\n/g, '\\n')
}

function block(map) {
	return Object.keys(map)
		.map((k) => `\t'${k}', '${esc(map[k])}',`)
		.join('\n')
}

